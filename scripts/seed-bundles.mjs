const places = PLACE_DEFS.map(([name, area, address, landmark], i) => {
  const id = `place-${String(i + 1).padStart(2, '0')}`
  const img = `/images/places/p${String(((i % 10) + 1)).padStart(2, '0')}.jpg`
  return {
    id,
    name,
    city: 'Ahmedabad',
    area,
    address,
    landmark,
    image: img,
    tags: ['Garba venue', area],
    capacityHint: 800 + (i % 12) * 150,
    parking: i % 3 !== 0,
    metroNearby: [1, 2, 11, 12, 27, 35, 36].includes(i + 1),
  }
})

function buildDays(placeIndexes, startDate) {
  return placeIndexes.map((pi, idx) => {
    const p = places[pi]
    const d = new Date(`${startDate}T12:00:00+05:30`)
    d.setDate(d.getDate() + idx)
    const date = d.toISOString().slice(0, 10)
    const [theme, dressHint] = THEMES[idx]
    return {
      day: idx + 1,
      date,
      placeId: p.id,
      venue: p.name,
      area: p.area,
      address: p.address,
      landmark: p.landmark,
      theme,
      dressHint,
      startTime: idx === 8 ? '18:30' : '19:00',
      endTime: idx === 8 ? '01:30' : '00:30',
      gatesOpen: '18:00',
      image: p.image,
      highlights: [
        `${theme} special décor`,
        `Venue: ${p.area}`,
        dressHint,
        p.metroNearby ? 'Metro / BRTS friendly' : 'Parking available nearby',
      ],
      note: `Day ${idx + 1} of 9 — show QR at ${p.landmark}`,
    }
  })
}

